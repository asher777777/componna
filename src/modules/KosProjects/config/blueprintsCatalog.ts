const BASE_CREATED_AT = '2026-01-01T00:00:00.000Z';

function addDays(days: number): string {
  const base = new Date('2026-01-01T00:00:00Z');
  base.setUTCDate(base.getUTCDate() + days);
  return base.toISOString().split('T')[0];
}

function task(
  order: number,
  phase: string,
  title: string,
  startOffset: number,
  durationDays: number,
  ownerRole: string,
  suppliers: Array<{ name: string; role: string; costEstimate?: number }> = [],
  opts: { isMilestone?: boolean; estimatedCost?: number; description?: string } = {}
): ProjectTaskDraft {
  return {
    phase,
    title,
    description: opts.description,
    startDate: addDays(startOffset),
    endDate: addDays(startOffset + Math.max(1, durationDays)),
    progress: 0,
    status: 'pending',
    ownerName: '',
    ownerRole,
    suppliers: suppliers.map((s) => ({
      name: s.name,
      role: s.role,
      isSupplier: true,
      costEstimate: s.costEstimate,
    })),
    dependsOnTaskIds: [],
    isMilestone: opts.isMilestone,
    estimatedCost: opts.estimatedCost,
    order,
  };
}

