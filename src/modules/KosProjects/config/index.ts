function addDaysIso(baseDate: string, days: number): string {
  const dt = new Date(baseDate);
  if (Number.isNaN(dt.getTime())) return baseDate;
  dt.setDate(dt.getDate() + days);
  return dt.toISOString().split('T')[0];
}

